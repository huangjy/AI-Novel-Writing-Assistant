#!/usr/bin/env python3
"""通过 mmdc 渲染 Mermaid，并生成可离线审阅的中文 HTML。"""

import argparse
import base64
import hashlib
import html
import json
import math
import os
from pathlib import Path
import re
import shutil
import struct
import subprocess
import sys
import tempfile
import xml.etree.ElementTree as ET
import zlib


MARKER = "<!-- Generated by dev-workflow/render_diagrams.py -->"
KINDS = {"dev-design": "技术方案与架构设计", "test-workflow": "端到端测试流程"}
GENERATOR = "dev-workflow/render_diagrams.py"


class RecoveryRequired(ValueError):
    pass


def run_cli(command, timeout):
    try:
        result = subprocess.run(
            command, capture_output=True, text=True, timeout=timeout, check=False
        )
    except (OSError, subprocess.TimeoutExpired) as error:
        raise ValueError(f"Mermaid CLI 无法运行：{error}") from error
    if result.returncode:
        detail = (result.stderr or result.stdout).strip()[-4000:]
        raise ValueError(f"Mermaid CLI 执行失败（退出码 {result.returncode}）：{detail}")
    return result.stdout.strip()


def svg_dimensions(path):
    try:
        root = ET.fromstring(path.read_bytes())
        box = [float(value) for value in root.attrib["viewBox"].split()]
    except (OSError, ET.ParseError, KeyError, ValueError) as error:
        raise ValueError(f"SVG 输出无效：{path.name}") from error
    if (
        root.tag.rsplit("}", 1)[-1] != "svg"
        or len(box) != 4
        or not all(math.isfinite(value) for value in box)
        or min(box[2:]) <= 0
    ):
        raise ValueError(f"SVG 视口为空或无效：{path.name}")
    visible = {"path", "text", "rect", "circle", "ellipse", "polygon", "line", "use", "image"}
    definitions = {"defs", "clipPath", "mask", "marker", "symbol", "pattern", "style", "script"}

    def painted(node):
        tag = node.tag.rsplit("}", 1)[-1]
        if tag in definitions or node.get("display") == "none":
            return False
        return tag in visible or any(painted(child) for child in node)

    if not painted(root):
        raise ValueError(f"SVG 中没有可绘制的图形元素：{path.name}")
    return math.ceil(box[2]), math.ceil(box[3])


def validate_png(path):
    try:
        data = path.read_bytes()
        if data[:8] != b"\x89PNG\r\n\x1a\n":
            raise ValueError("signature")
        offset, chunks, compressed = 8, [], []
        while offset < len(data):
            size = struct.unpack(">I", data[offset:offset + 4])[0]
            kind = data[offset + 4:offset + 8]
            end = offset + size + 12
            if end > len(data):
                raise ValueError("truncated chunk")
            payload = data[offset + 8:end - 4]
            checksum = struct.unpack(">I", data[end - 4:end])[0]
            if zlib.crc32(kind + payload) != checksum:
                raise ValueError("checksum")
            chunks.append(kind)
            if kind == b"IHDR":
                width, height, depth, color, compression, filtering, interlace = (
                    struct.unpack(">IIBBBBB", payload)
                )
            elif kind == b"IDAT":
                compressed.append(payload)
            offset = end
            if kind == b"IEND":
                if size or offset != len(data):
                    raise ValueError("invalid end")
                break
        if (
            not chunks or chunks[0] != b"IHDR" or chunks.count(b"IHDR") != 1
            or chunks[-1] != b"IEND" or not compressed or min(width, height) <= 0
            or compression or filtering or interlace not in (0, 1)
        ):
            raise ValueError("missing PNG structure")
        depths = {0: (1, 2, 4, 8, 16), 2: (8, 16), 3: (1, 2, 4, 8), 4: (8, 16), 6: (8, 16)}
        if depth not in depths.get(color, ()) or (color == 3 and b"PLTE" not in chunks):
            raise ValueError("unsupported PNG header")
        channels = {0: 1, 2: 3, 3: 1, 4: 2, 6: 4}[color]
        passes = [(0, 0, 1, 1)] if not interlace else [
            (0, 0, 8, 8), (4, 0, 8, 8), (0, 4, 4, 8), (2, 0, 4, 4),
            (0, 2, 2, 4), (1, 0, 2, 2), (0, 1, 1, 2),
        ]
        rows = []
        for x, y, dx, dy in passes:
            w, h = max(0, (width - x + dx - 1) // dx), max(0, (height - y + dy - 1) // dy)
            if w and h:
                rows.append(((w * channels * depth + 7) // 8 + 1, h))
        expected = sum(length * count for length, count in rows)
        decoder = zlib.decompressobj()
        pixels = decoder.decompress(b"".join(compressed), expected + 1)
        if len(pixels) != expected or not decoder.eof or decoder.unused_data or decoder.unconsumed_tail:
            raise ValueError("incomplete pixel stream")
        offset = 0
        for length, count in rows:
            if any(pixels[offset + index * length] > 4 for index in range(count)):
                raise ValueError("invalid row filter")
            offset += length * count
    except (OSError, ValueError, struct.error, zlib.error, UnboundLocalError) as error:
        raise ValueError(f"PNG 输出无效：{path.name}") from error


def load_ownership(manifest):
    if not manifest.exists():
        return {}
    if manifest.is_symlink() or not manifest.is_file():
        raise ValueError(f"拒绝使用非文件类型的渲染记录：{manifest}")
    try:
        record = json.loads(manifest.read_text(encoding="utf-8"))
        artifacts = record["artifacts"]
        if record["generated_by"] != GENERATOR or not isinstance(artifacts, dict):
            raise ValueError("not generated by this helper")
        if not all(
            isinstance(name, str) and Path(name).name == name
            and isinstance(digest, str) and re.fullmatch(r"[a-f0-9]{64}", digest)
            for name, digest in artifacts.items()
        ):
            raise ValueError("invalid ownership entries")
        return {
            **artifacts,
            manifest.name: hashlib.sha256(manifest.read_bytes()).hexdigest(),
        }
    except (ValueError, KeyError, TypeError) as error:
        raise ValueError(f"文件归属记录无效：{manifest}") from error


def check_targets(targets, manifest, ownership):
    for target in targets:
        if target.is_symlink() or (target.exists() and not target.is_file()):
            raise ValueError(f"拒绝使用非文件类型的目标路径：{target}")
        if target.exists():
            digest = hashlib.sha256(target.read_bytes()).hexdigest()
            if ownership.get(target.name) != digest:
                raise ValueError(f"拒绝覆盖不属于本次渲染或已被修改的文件：{target}")


def publish(staged, output, manifest, ownership):
    targets = [output / source.name for source in staged]
    check_targets(targets, manifest, ownership)
    backup = staged[0].parent / "rollback"
    backup.mkdir()
    existing = {}
    for target in targets:
        if target.exists():
            saved = backup / target.name
            shutil.copyfile(target, saved)
            existing[target] = saved
    committed = []
    try:
        for source, target in zip(staged, targets):
            os.replace(source, target)
            committed.append(target)
    except OSError as error:
        failures = []
        for target in reversed(committed):
            try:
                if target in existing:
                    os.replace(existing[target], target)
                else:
                    target.unlink()
            except OSError:
                failures.append(str(target))
        if failures:
            raise RecoveryRequired(
                f"附件发布失败；恢复副本保留在 {backup}，请检查：{failures}"
            ) from error
        raise ValueError(f"附件发布失败；已恢复原有附件：{error}") from error


def build_html(title, kind, version, diagrams):
    sections = []
    for index, item in enumerate(diagrams, start=1):
        encoded = base64.b64encode(item["svg"]).decode("ascii")
        label = html.escape(f"图 {index}：{item['label']}")
        sections.append(
            f'<section><h2>{label}</h2><div class="diagram">'
            f'<img alt="{label}" width="{item["width"]}" height="{item["height"]}" '
            f'src="data:image/svg+xml;base64,{encoded}"></div>'
            f'<details><summary>Mermaid 源码</summary><pre><code>'
            f'{html.escape(item["source"])}</code></pre></details>'
            f'<p class="meta">源码 SHA-256：{item["sha256"]}</p></section>'
        )
    heading = html.escape(f"{title} - {KINDS[kind]}")
    return f"""<!doctype html>
{MARKER}
<html lang="zh-CN"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{heading}</title>
<style>
* {{ box-sizing: border-box; letter-spacing: 0; }}
body {{ margin: 0; color: #17201c; background: #fff;
  font: 16px/1.5 system-ui, sans-serif; }}
main {{ max-width: 1440px; margin: auto; padding: 24px; }}
h1 {{ font-size: 24px; overflow-wrap: anywhere; }}
h2 {{ font-size: 18px; overflow-wrap: anywhere; }}
section {{ padding: 20px 0; border-top: 1px solid #d5ded8; }}
.diagram {{ overflow: auto; max-width: 100%; background: #fff; }}
.diagram img {{ display: block; max-width: none; }}
details {{ margin-top: 16px; }}
pre {{ overflow: auto; padding: 12px; background: #f1f5f2; }}
.meta {{ color: #526158; font-size: 12px; overflow-wrap: anywhere; }}
@media (max-width: 600px) {{ main {{ padding: 12px; }} }}
</style></head><body><main><h1>{heading}</h1>
<p class="meta">Mermaid CLI 版本：{html.escape(version)}</p>
{"".join(sections)}
</main></body></html>
"""


def render(args):
    if not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", args.feature):
        raise ValueError("--feature 必须使用 ASCII 小写短横线名称（kebab-case）")
    if args.timeout <= 0:
        raise ValueError("--timeout 必须大于 0")
    executable = shutil.which(args.mmdc)
    if not executable:
        raise ValueError("未找到 Mermaid CLI；请通过 --mmdc 提供已安装的 mmdc 路径")
    sources = []
    for name in args.source:
        path = Path(name).resolve()
        try:
            text = path.read_bytes().decode("utf-8")
        except OSError as error:
            raise ValueError(f"无法读取 Mermaid 源码：{path}") from error
        if not text.strip():
            raise ValueError(f"Mermaid 源码为空：{path}")
        sources.append((path, text))
    out = Path(args.output_dir).resolve()
    out.mkdir(parents=True, exist_ok=True)
    stem = f"{args.feature}-{args.kind}"
    page = out / f"{stem}.html"
    manifest = out / f"{stem}.render.json"
    ownership = load_ownership(manifest)
    names = []
    for index in range(len(sources)):
        suffix = f"-{index + 1:02d}" if len(sources) > 1 else ""
        names.append(f"{stem}{suffix}")
    targets = [page, manifest] + [
        out / f"{name}.{extension}"
        for name in names
        for extension in (["svg", "png"] if args.png else ["svg"])
    ]
    check_targets(targets, manifest, ownership)
    version = run_cli([executable, "--version"], args.timeout)
    if not version:
        raise ValueError("Mermaid CLI 未返回版本号")
    records = []
    diagrams = []
    # Publish only after every requested diagram and format has rendered.
    stage = Path(tempfile.mkdtemp(prefix=".mermaid-", dir=out))
    retain_recovery = False
    try:
        config = stage / "mermaid-config.json"
        config.write_text(
            json.dumps({
                "securityLevel": "strict", "htmlLabels": False,
                "flowchart": {"htmlLabels": False},
            }),
            encoding="utf-8",
        )
        staged = []
        for (source, text), name in zip(sources, names):
            staged_source = stage / f"{name}.mmd"
            staged_source.write_text(text, encoding="utf-8")
            for extension in (["svg", "png"] if args.png else ["svg"]):
                image = stage / f"{name}.{extension}"
                command = [
                    executable, "-i", str(staged_source), "-o", str(image),
                    "-b", "white", "-c", str(config),
                ]
                if args.puppeteer_config:
                    command.extend(["-p", str(Path(args.puppeteer_config).resolve())])
                if extension == "png":
                    command.extend(["-s", "2"])
                run_cli(command, args.timeout)
                if extension == "svg":
                    width, height = svg_dimensions(image)
                else:
                    validate_png(image)
                staged.append(image)
            digest = hashlib.sha256(text.encode("utf-8")).hexdigest()
            diagrams.append({
                "label": source.stem, "source": text, "sha256": digest,
                "svg": (stage / f"{name}.svg").read_bytes(),
                "width": width, "height": height,
            })
            records.append({
                "source": str(source), "sha256": digest,
                "svg": str(out / f"{name}.svg"),
                **({"png": str(out / f"{name}.png")} if args.png else {}),
            })
        staged_page = stage / page.name
        staged_page.write_text(
            build_html(args.title or args.feature, args.kind, version, diagrams),
            encoding="utf-8",
        )
        staged.append(staged_page)
        result = {
            "generated_by": GENERATOR, "html": str(page), "manifest": str(manifest),
            "mermaid_cli_version": version, "diagrams": records,
            "artifacts": {
                item.name: hashlib.sha256(item.read_bytes()).hexdigest() for item in staged
            },
        }
        staged_manifest = stage / manifest.name
        staged_manifest.write_text(json.dumps(result, indent=2) + "\n", encoding="utf-8")
        staged.append(staged_manifest)
        publish(staged, out, manifest, ownership)
    except RecoveryRequired:
        retain_recovery = True
        raise
    finally:
        if not retain_recovery:
            shutil.rmtree(stage)
    return result


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, add_help=False)
    parser.add_argument("-h", "--help", action="help", help="显示帮助信息并退出")
    parser.add_argument("--feature", required=True, help="用于文件名的 feature 标识")
    parser.add_argument("--kind", required=True, choices=KINDS, help="开发设计或测试流程")
    parser.add_argument("--source", required=True, action="append", help="Mermaid 源文件，可重复指定")
    parser.add_argument("--output-dir", required=True, help="附件输出目录")
    parser.add_argument("--title", help="中文展示标题")
    parser.add_argument("--png", action="store_true", help="同时生成 PNG 预览")
    parser.add_argument("--mmdc", default="mmdc", help="Mermaid CLI 可执行文件路径")
    parser.add_argument("--puppeteer-config", help="浏览器配置 JSON 路径")
    parser.add_argument("--timeout", type=int, default=120, help="每次 CLI 调用超时秒数")
    args = parser.parse_args(argv)
    try:
        result = render(args)
    except (ValueError, OSError) as error:
        print(f"渲染失败：{error}", file=sys.stderr)
        return 1
    print(json.dumps(result, ensure_ascii=True, indent=2))
    return 0


if __name__ == "__main__":
    sys.exit(main())
